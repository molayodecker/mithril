#!/usr/bin/env bash
set -euo pipefail

for command_name in psql python3; do
  if ! command -v "$command_name" >/dev/null 2>&1; then
    echo "$command_name is required for the missing-row merge test." >&2
    exit 1
  fi
done

ADMIN_URL="${DB_SYNC_TEST_ADMIN_URL:-postgresql://postgres:postgres@localhost:5432/postgres}"
SOURCE_DB="mithril_merge_source"
TARGET_DB="mithril_merge_target"
ADMIN_PREFIX="${ADMIN_URL%/*}"
SOURCE_URL="$ADMIN_PREFIX/$SOURCE_DB"
TARGET_URL="$ADMIN_PREFIX/$TARGET_DB"
ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP_DIR="$(mktemp -d)"
READY_FILE="$TMP_DIR/snapshot-ready"
RELEASE_FILE="$TMP_DIR/snapshot-release"
APPLY_LOG="$TMP_DIR/apply.log"
MERGE_PID=""

USER_A="11111111-1111-1111-1111-111111111111"
USER_B="22222222-2222-2222-2222-222222222222"
USER_C="33333333-3333-3333-3333-333333333333"
USER_LATE="dddddddd-dddd-dddd-dddd-dddddddddddd"
BOOKING_B="55555555-5555-5555-5555-555555555555"
BOOKING_C="66666666-6666-6666-6666-666666666666"
BOOKING_ORPHAN="44444444-4444-4444-4444-444444444444"
ORPHAN_CUSTOMER="00000000-0000-0000-0000-000000000099"
CATEGORY_ROOT="77777777-7777-7777-7777-777777777777"
CATEGORY_CHILD="88888888-8888-8888-8888-888888888888"
LABEL_TARGET="99999999-9999-9999-9999-999999999999"
LABEL_CONFLICT="aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa"
LABEL_FRESH="bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb"
SECRET_ROW="cccccccc-cccc-cccc-cccc-cccccccccccc"

cleanup() {
  if [[ -n "${MERGE_PID:-}" ]]; then
    kill "$MERGE_PID" >/dev/null 2>&1 || true
    wait "$MERGE_PID" >/dev/null 2>&1 || true
  fi
  psql "$ADMIN_URL" -X -q -v ON_ERROR_STOP=1 -c "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname IN ('$SOURCE_DB', '$TARGET_DB') AND pid <> pg_backend_pid();" >/dev/null 2>&1 || true
  psql "$ADMIN_URL" -X -q -v ON_ERROR_STOP=1 -c "DROP DATABASE IF EXISTS $SOURCE_DB;" >/dev/null 2>&1 || true
  psql "$ADMIN_URL" -X -q -v ON_ERROR_STOP=1 -c "DROP DATABASE IF EXISTS $TARGET_DB;" >/dev/null 2>&1 || true
  psql "$ADMIN_URL" -X -q -v ON_ERROR_STOP=1 -c "DROP ROLE IF EXISTS merge_writer;" >/dev/null 2>&1 || true
  psql "$ADMIN_URL" -X -q -v ON_ERROR_STOP=1 -c "DROP ROLE IF EXISTS merge_other;" >/dev/null 2>&1 || true
  rm -rf "$TMP_DIR"
}
trap cleanup EXIT

if grep -E 'DELETE FROM|TRUNCATE|DROP TABLE|UPDATE ' "$ROOT_DIR/scripts/db_sync_merge_missing.py"; then
  echo "Insert-only merge script contains a destructive statement." >&2
  exit 1
fi

if SOURCE_DATABASE_URL="$SOURCE_URL" \
  TARGET_DATABASE_URL="$SOURCE_URL" \
  CONFIRM_MISSING_MERGE=YES \
  bash "$ROOT_DIR/scripts/db_sync_merge_missing.sh" >/dev/null 2>"$TMP_DIR/identical.err"; then
  echo "Merge should refuse when source and target are the same database." >&2
  exit 1
fi
if ! grep -q "identical" "$TMP_DIR/identical.err"; then
  echo "Identical-database refusal did not explain why." >&2
  exit 1
fi

if SOURCE_DATABASE_URL="$SOURCE_URL" \
  TARGET_DATABASE_URL="postgresql://postgres:postgres@db.example.supabase.co:5432/postgres" \
  CONFIRM_MISSING_MERGE=YES \
  bash "$ROOT_DIR/scripts/db_sync_merge_missing.sh" >/dev/null 2>"$TMP_DIR/supabase.err"; then
  echo "Merge should refuse to write to Supabase." >&2
  exit 1
fi
if ! grep -q "Supabase" "$TMP_DIR/supabase.err"; then
  echo "Supabase-target refusal did not explain why." >&2
  exit 1
fi

PGOPTIONS="${PGOPTIONS:-} -c client_min_messages=warning" \
  psql "$ADMIN_URL" -X -q -v ON_ERROR_STOP=1 >/dev/null <<SQL
SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname IN ('$SOURCE_DB', '$TARGET_DB') AND pid <> pg_backend_pid();
DROP DATABASE IF EXISTS $SOURCE_DB;
DROP DATABASE IF EXISTS $TARGET_DB;
CREATE DATABASE $SOURCE_DB;
CREATE DATABASE $TARGET_DB;
SQL

SCHEMA_SQL=$(cat <<'SQL'
CREATE SCHEMA auth;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY,
  email text,
  phone text,
  encrypted_password text,
  recovery_token text,
  created_at timestamptz,
  updated_at timestamptz,
  is_anonymous boolean DEFAULT false
);

CREATE TABLE public.users (
  id uuid PRIMARY KEY REFERENCES auth.users(id),
  email text NOT NULL,
  note text
);

CREATE TABLE public.categories (
  id uuid PRIMARY KEY,
  name text NOT NULL,
  parent_id uuid REFERENCES public.categories(id)
);

CREATE TABLE public.bookings (
  id uuid PRIMARY KEY,
  customer_id uuid NOT NULL REFERENCES public.users(id),
  status text NOT NULL
);

CREATE TABLE public.invoices (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label text NOT NULL
);

CREATE TABLE public.labels (
  id uuid PRIMARY KEY,
  name text NOT NULL UNIQUE
);

CREATE TABLE public.secrets_blocked (
  id uuid PRIMARY KEY,
  password text NOT NULL
);

CREATE TABLE public.notes_without_pk (
  body text
);
SQL
)

psql "$SOURCE_URL" -X -q -v ON_ERROR_STOP=1 <<<"$SCHEMA_SQL"
psql "$TARGET_URL" -X -q -v ON_ERROR_STOP=1 <<<"$SCHEMA_SQL"
psql "$TARGET_URL" -X -q -v ON_ERROR_STOP=1 <<'SQL'
CREATE TABLE public.target_only_marker (
  id integer PRIMARY KEY,
  label text NOT NULL
);
INSERT INTO public.target_only_marker (id, label) VALUES (1, 'keep-me');
SQL

psql "$SOURCE_URL" -X -q -v ON_ERROR_STOP=1 <<SQL
INSERT INTO auth.users (id, email, encrypted_password, recovery_token)
VALUES
  ('$USER_A', 'source-a@example.com', 'SECRET_SOURCE', 'SECRET_RECOVERY'),
  ('$USER_B', 'source-b@example.com', 'SECRET_NEW', 'SECRET_RECOVERY_NEW');

INSERT INTO public.users (id, email, note)
VALUES
  ('$USER_A', 'source-a@example.com', 'from-source'),
  ('$USER_B', 'source-b@example.com', 'from-source-b');

INSERT INTO public.categories (id, name, parent_id)
VALUES
  ('$CATEGORY_ROOT', 'source-root', NULL),
  ('$CATEGORY_CHILD', 'child', '$CATEGORY_ROOT');

INSERT INTO public.bookings (id, customer_id, status)
VALUES ('$BOOKING_B', '$USER_B', 'source-open');

ALTER TABLE public.bookings DROP CONSTRAINT bookings_customer_id_fkey;
INSERT INTO public.bookings (id, customer_id, status)
VALUES ('$BOOKING_ORPHAN', '$ORPHAN_CUSTOMER', 'orphan');

INSERT INTO public.invoices (id, label) OVERRIDING SYSTEM VALUE
VALUES (1, 'source-invoice'), (5, 'source-five');

INSERT INTO public.labels (id, name)
VALUES
  ('$LABEL_CONFLICT', 'taken'),
  ('$LABEL_FRESH', 'fresh');

INSERT INTO public.secrets_blocked (id, password)
VALUES ('$SECRET_ROW', 'do-not-copy');

INSERT INTO public.notes_without_pk (body)
VALUES ('source-note');
SQL

psql "$TARGET_URL" -X -q -v ON_ERROR_STOP=1 >/dev/null <<SQL
INSERT INTO auth.users (id, email, encrypted_password)
VALUES
  ('$USER_A', 'target-a@example.com', 'TARGET_HASH'),
  ('$USER_C', 'target-c@example.com', 'TARGET_C_HASH');

INSERT INTO public.users (id, email, note)
VALUES
  ('$USER_A', 'target-a@example.com', 'from-target'),
  ('$USER_C', 'target-c@example.com', 'target-only');

INSERT INTO public.categories (id, name)
VALUES ('$CATEGORY_ROOT', 'target-root');

INSERT INTO public.bookings (id, customer_id, status)
VALUES ('$BOOKING_C', '$USER_C', 'target-open');

INSERT INTO public.invoices (id, label) OVERRIDING SYSTEM VALUE
VALUES (1, 'target-invoice'), (9, 'target-only-invoice');

SELECT setval(pg_get_serial_sequence('public.invoices', 'id'), 3, true);

INSERT INTO public.labels (id, name)
VALUES ('$LABEL_TARGET', 'taken');
SQL

SOURCE_BEFORE="$(psql "$SOURCE_URL" -X -Atqc "SELECT id::text || '|' || email || '|' || encrypted_password || '|' || recovery_token FROM auth.users ORDER BY id")"

SOURCE_DATABASE_URL="$SOURCE_URL" \
  TARGET_DATABASE_URL="$TARGET_URL" \
  CONFIRM_MISSING_MERGE=YES \
  DRY_RUN=YES \
  bash "$ROOT_DIR/scripts/db_sync_merge_missing.sh" >"$TMP_DIR/dry-run.log"

if ! grep -q "Dry run only" "$TMP_DIR/dry-run.log"; then
  echo "CONFIRM_MISSING_MERGE with DRY_RUN=YES still wrote, or the dry-run banner was missing." >&2
  exit 1
fi
if ! grep -q $'public.users\tdry_run\t2\t1\t' "$TMP_DIR/dry-run.log"; then
  echo "Dry run did not report the missing source user." >&2
  cat "$TMP_DIR/dry-run.log" >&2
  exit 1
fi
if ! grep -q $'public.secrets_blocked\tskipped_required_column\t' "$TMP_DIR/dry-run.log"; then
  echo "Dry run should refuse a required secret column instead of planning to copy it." >&2
  exit 1
fi
if ! grep -q $'public.target_only_marker\ttarget_only_untouched\t' "$TMP_DIR/dry-run.log"; then
  echo "Dry run should leave target-only tables untouched." >&2
  exit 1
fi
if ! grep -q "result=dry_run missing_rows=.* needs_review=yes" "$TMP_DIR/dry-run.log"; then
  echo "Dry run should report missing keys and rows that need review." >&2
  cat "$TMP_DIR/dry-run.log" >&2
  exit 1
fi

TARGET_AFTER_DRY="$(psql "$TARGET_URL" -X -Atqc "SELECT email || '|' || note FROM public.users WHERE id = '$USER_A'")"
if [[ "$TARGET_AFTER_DRY" != "target-a@example.com|from-target" ]]; then
  echo "Dry run changed an existing target row: $TARGET_AFTER_DRY" >&2
  exit 1
fi

WRITER_URL="postgresql://merge_writer:merge_writer@${ADMIN_PREFIX#*@}/$TARGET_DB"
psql "$TARGET_URL" -X -q -v ON_ERROR_STOP=1 >/dev/null 2>&1 <<SQL
DO \$\$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'merge_writer') THEN
    CREATE ROLE merge_writer LOGIN PASSWORD 'merge_writer' NOSUPERUSER NOBYPASSRLS NOCREATEDB;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'merge_other') THEN
    CREATE ROLE merge_other NOLOGIN;
  END IF;
END
\$\$;
GRANT CONNECT, CREATE ON DATABASE $TARGET_DB TO merge_writer;
GRANT USAGE, CREATE ON SCHEMA public, auth TO merge_writer;
GRANT ALL ON ALL TABLES IN SCHEMA public, auth TO merge_writer;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public, auth TO merge_writer;
DO \$\$
DECLARE
  rel record;
BEGIN
  FOR rel IN
    SELECT n.nspname, c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname IN ('public', 'auth')
      AND c.relkind = 'r'
  LOOP
    EXECUTE format('ALTER TABLE %I.%I OWNER TO merge_writer', rel.nspname, rel.relname);
  END LOOP;
END
\$\$;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS bookings_other_select ON public.bookings;
DROP POLICY IF EXISTS bookings_other_insert ON public.bookings;
CREATE POLICY bookings_other_select ON public.bookings FOR SELECT TO merge_other USING (true);
CREATE POLICY bookings_other_insert ON public.bookings FOR INSERT TO merge_other WITH CHECK (true);
SQL

SOURCE_DATABASE_URL="$SOURCE_URL" \
  TARGET_DATABASE_URL="$WRITER_URL" \
  CONFIRM_MISSING_MERGE=YES \
  MERGE_SNAPSHOT_READY_FILE="$READY_FILE" \
  MERGE_SNAPSHOT_RELEASE_FILE="$RELEASE_FILE" \
  bash "$ROOT_DIR/scripts/db_sync_merge_missing.sh" >"$APPLY_LOG" 2>"$TMP_DIR/apply.err" &
MERGE_PID=$!

for _ in $(seq 1 200); do
  [[ -s "$READY_FILE" ]] && break
  if ! kill -0 "$MERGE_PID" >/dev/null 2>&1; then
    echo "Merge exited before exporting its snapshot." >&2
    cat "$APPLY_LOG" "$TMP_DIR/apply.err" >&2
    exit 1
  fi
  sleep 0.05
done
if [[ ! -s "$READY_FILE" ]]; then
  echo "Merge did not export a snapshot in time." >&2
  exit 1
fi

psql "$SOURCE_URL" -X -q -v ON_ERROR_STOP=1 <<SQL
INSERT INTO auth.users (id, email, encrypted_password)
VALUES ('$USER_LATE', 'late@example.com', 'LATE_SECRET');
INSERT INTO public.users (id, email, note)
VALUES ('$USER_LATE', 'late@example.com', 'late');
SQL

touch "$RELEASE_FILE"
set +e
wait "$MERGE_PID"
APPLY_STATUS=$?
set -e
MERGE_PID=""

if [[ "$APPLY_STATUS" -ne 2 ]]; then
  echo "Apply should exit 2 when some source rows cannot be inserted. Got $APPLY_STATUS." >&2
  cat "$APPLY_LOG" "$TMP_DIR/apply.err" >&2
  exit 1
fi

q() {
  psql "$TARGET_URL" -X -Atqc "$1"
}

if [[ "$(q "SELECT email || '|' || note FROM public.users WHERE id = '$USER_A'")" != "target-a@example.com|from-target" ]]; then
  echo "Existing target user was overwritten." >&2
  exit 1
fi
if [[ "$(q "SELECT email || '|' || coalesce(encrypted_password, '<null>') FROM auth.users WHERE id = '$USER_A'")" != "target-a@example.com|TARGET_HASH" ]]; then
  echo "Existing target password or email was overwritten." >&2
  exit 1
fi
if [[ "$(q "SELECT email || '|' || note || '|' || coalesce((SELECT encrypted_password FROM auth.users a WHERE a.id = public.users.id), '<null>') FROM public.users WHERE id = '$USER_B'")" != "source-b@example.com|from-source-b|<null>" ]]; then
  echo "Missing source user was not inserted without the password hash." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM public.users WHERE id = '$USER_C'")" != "1" ]]; then
  echo "Target-only user was removed." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM public.users WHERE id = '$USER_LATE'")" != "0" ]]; then
  echo "Row committed after the snapshot was copied." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM auth.users WHERE encrypted_password LIKE 'SECRET%' OR encrypted_password LIKE 'LATE%'")" != "0" ]]; then
  echo "Source auth secret appeared on the target." >&2
  exit 1
fi
if [[ "$(q "SELECT name FROM public.categories WHERE id = '$CATEGORY_ROOT'")" != "target-root" ]]; then
  echo "Existing category name was overwritten." >&2
  exit 1
fi
if [[ "$(q "SELECT name FROM public.categories WHERE id = '$CATEGORY_CHILD'")" != "child" ]]; then
  echo "Missing child category was not inserted." >&2
  exit 1
fi
if [[ "$(q "SELECT status FROM public.bookings WHERE id = '$BOOKING_B'")" != "source-open" ]]; then
  echo "Missing booking was not inserted." >&2
  exit 1
fi
if [[ "$(q "SELECT status FROM public.bookings WHERE id = '$BOOKING_C'")" != "target-open" ]]; then
  echo "Target-only booking was removed." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM public.bookings WHERE id = '$BOOKING_ORPHAN'")" != "0" ]]; then
  echo "Booking with a missing parent was inserted." >&2
  exit 1
fi
if [[ "$(q "SELECT label FROM public.invoices WHERE id = 1")" != "target-invoice" ]]; then
  echo "Existing invoice was overwritten." >&2
  exit 1
fi
if [[ "$(q "SELECT label FROM public.invoices WHERE id = 5")" != "source-five" ]]; then
  echo "Missing invoice was not inserted." >&2
  exit 1
fi
if [[ "$(q "SELECT label FROM public.invoices WHERE id = 9")" != "target-only-invoice" ]]; then
  echo "Target-only invoice was removed." >&2
  exit 1
fi
SEQUENCE_STATE="$(q "SELECT last_value::text || ',' || is_called::text FROM public.invoices_id_seq")"
if [[ "$SEQUENCE_STATE" != "9,true" ]]; then
  echo "Invoice sequence should stay at the higher target value, got $SEQUENCE_STATE." >&2
  exit 1
fi
if [[ "$(q "SELECT id::text FROM public.labels WHERE name = 'taken'")" != "$LABEL_TARGET" ]]; then
  echo "Unique label conflict replaced the target row." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM public.labels WHERE id = '$LABEL_FRESH'")" != "1" ]]; then
  echo "Non-conflicting label was not inserted." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM public.secrets_blocked")" != "0" ]]; then
  echo "Required secret column was copied." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM public.notes_without_pk")" != "0" ]]; then
  echo "Table without a primary key was copied." >&2
  exit 1
fi
if [[ "$(q "SELECT label FROM public.target_only_marker WHERE id = 1")" != "keep-me" ]]; then
  echo "Target-only table was changed." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM pg_namespace WHERE nspname LIKE 'merge_missing_%'")" != "0" ]]; then
  echo "Staging schema was left behind on the target." >&2
  exit 1
fi
if [[ "$(q "SELECT count(*) FROM pg_policy WHERE polname IN ('merge_missing_select', 'merge_missing_insert')")" != "0" ]]; then
  echo "Temporary row-access policies were left behind." >&2
  exit 1
fi

SOURCE_AFTER="$(psql "$SOURCE_URL" -X -Atqc "SELECT id::text || '|' || email || '|' || encrypted_password || '|' || recovery_token FROM auth.users WHERE id IN ('$USER_A', '$USER_B') ORDER BY id")"
if [[ "$SOURCE_AFTER" != "$SOURCE_BEFORE" ]]; then
  echo "Source rows were modified." >&2
  echo "before: $SOURCE_BEFORE" >&2
  echo "after:  $SOURCE_AFTER" >&2
  exit 1
fi

if [[ "$(q "SELECT count(*) FROM public.users WHERE id = '$USER_LATE'")" != "0" ]]; then
  echo "Row committed after the snapshot was copied on the first apply." >&2
  exit 1
fi

set +e
SOURCE_DATABASE_URL="$SOURCE_URL" \
  TARGET_DATABASE_URL="$WRITER_URL" \
  CONFIRM_MISSING_MERGE=YES \
  bash "$ROOT_DIR/scripts/db_sync_merge_missing.sh" >"$TMP_DIR/second.log" 2>"$TMP_DIR/second.err"
SECOND_STATUS=$?
set -e
if [[ "$SECOND_STATUS" -ne 2 ]]; then
  echo "Second apply should copy the row committed after the first snapshot and still report incomplete rows. Got $SECOND_STATUS." >&2
  cat "$TMP_DIR/second.log" "$TMP_DIR/second.err" >&2
  exit 1
fi
if [[ "$(q "SELECT email || '|' || coalesce(encrypted_password, '<null>') FROM auth.users WHERE id = '$USER_LATE'")" != "late@example.com|<null>" ]]; then
  echo "Late source user should arrive on the next run without a password hash." >&2
  exit 1
fi
if [[ "$(q "SELECT note FROM public.users WHERE id = '$USER_LATE'")" != "late" ]]; then
  echo "Late source profile should arrive on the next run." >&2
  exit 1
fi
if [[ "$(q "SELECT email || '|' || note FROM public.users WHERE id = '$USER_A'")" != "target-a@example.com|from-target" ]]; then
  echo "Second apply overwrote the existing target user." >&2
  exit 1
fi

TARGET_COUNTS="$(q "SELECT (SELECT count(*) FROM public.users) || ',' || (SELECT count(*) FROM public.bookings) || ',' || (SELECT count(*) FROM public.labels)")"

set +e
SOURCE_DATABASE_URL="$SOURCE_URL" \
  TARGET_DATABASE_URL="$WRITER_URL" \
  CONFIRM_MISSING_MERGE=YES \
  bash "$ROOT_DIR/scripts/db_sync_merge_missing.sh" >"$TMP_DIR/third.log" 2>"$TMP_DIR/third.err"
THIRD_STATUS=$?
set -e
if [[ "$THIRD_STATUS" -ne 2 ]]; then
  echo "Third apply should insert nothing new while blocked rows remain. Got $THIRD_STATUS." >&2
  cat "$TMP_DIR/third.log" "$TMP_DIR/third.err" >&2
  exit 1
fi
TARGET_COUNTS_AGAIN="$(q "SELECT (SELECT count(*) FROM public.users) || ',' || (SELECT count(*) FROM public.bookings) || ',' || (SELECT count(*) FROM public.labels)")"
if [[ "$TARGET_COUNTS_AGAIN" != "$TARGET_COUNTS" ]]; then
  echo "Third apply changed row counts: $TARGET_COUNTS -> $TARGET_COUNTS_AGAIN" >&2
  exit 1
fi

echo "✓ insert-only missing-row merge test passed"
